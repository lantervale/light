package dom

// opRemove is the operation that takes a node out of its parent.
const opRemove = "remove"

// table is every operation scripts ask of light, by its name.
func (r *Runtime) table() map[string]op {
	return map[string]op{
		// the tree (tree.go)
		"doc":           r.document,
		"top":           r.topLevel,
		"tag":           r.of(r.tag),
		"parent":        r.of(r.parent),
		"children":      r.of(r.children),
		"child":         r.of(r.child),
		"sibling":       r.of(r.sibling),
		"connected":     r.of(r.isConnected),
		"contains":      r.of(r.contains),
		"compare":       r.of(r.compare),
		"create":        r.create,
		"createText":    r.createText,
		"createComment": r.createComment,
		"insert":        r.of(r.insert),
		opRemove:        r.of(r.remove),
		"clone":         r.of(r.clone),
		"content":       r.of(r.content),
		"text":          r.of(r.text),
		"setText":       r.of(r.setText),
		"html":          r.of(r.html),
		"setHTML":       r.of(r.setHTML),
		"fragment":      r.fragment,
		"query":         r.query,
		"matches":       r.of(r.matches),
		"closest":       r.of(r.closest),
		"byId":          r.byID,
		"handles":       r.held,
		"release":       r.let,
		// elements (element.go)
		"attr":         r.of(r.attr),
		"setAttr":      r.of(r.setAttr),
		"removeAttr":   r.of(r.removeAttr),
		"attrs":        r.of(r.attrs),
		"value":        r.on(r.value),
		"setValue":     r.on(r.setValue),
		checked:        r.on(r.checked),
		"setChecked":   r.on(r.setChecked),
		"selected":     r.on(r.selected),
		"selectedText": r.selectedText,
		"setSelected":  r.on(r.setSelected),
		"selection":    r.on(r.selection),
		selects:        r.on(r.selectRange),
		"focus":        r.on(r.focus),
		"blur":         r.on(r.blur),
		"active":       r.active,
		"activate":     r.on(r.activated),
		submit:         r.on(r.submitForm),
		"box":          r.on(r.box),
		"laid":         r.on(r.laid),
		"reveal":       r.on(r.reveal),
		"at":           r.at,
		// the window (window.go)
		"viewport":   r.viewport,
		"scroll":     r.scroll,
		"title":      r.title,
		"setTitle":   r.setTitle,
		"cookie":     r.cookie,
		"setCookie":  r.setCookie,
		"canCookie":  r.cookieEnabled,
		"log":        r.log,
		"clear":      r.clear,
		"uncaught":   r.uncaught,
		"where":      r.where,
		"now":        func(arguments) (any, error) { return r.now(), nil },
		"address":    func(arguments) (any, error) { return r.page.Address, nil },
		"navigator":  r.navigator,
		"around":     r.around,
		"navigate":   r.navigate,
		"reload":     r.reload,
		"history":    r.history,
		"go":         r.travel,
		"url":        parsed,
		"urlWith":    changed,
		"fetch":      r.fetch,
		"abortFetch": r.abort,
		"storage":    r.storage,
		"atob":       atob,
		"btoa":       btoa,
		"utf8":       utf8Into,
		"text8":      decoded,
		"body":       r.answered,
		"random":     random,
		// the site's databases (indexeddb.go)
		"idb": r.idb,
		// the other windows (windows.go)
		"window":  r.window,
		"origin":  func(arguments) (any, error) { return r.origin(), nil },
		"sandbox": func(arguments) (any, error) { return []bool{r.host.Sandboxed.Opaque, r.host.Sandboxed.NoModals}, nil },
	}
}
